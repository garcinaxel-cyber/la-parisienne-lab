"""Generate public/ui-themes/<id>.css — staff colour themes (Axel, 2026-11-13).
Every warm neutral of the Ivoire & cacao palette is re-tinted at the same lightness, so contrast
stays the same; alert reds / greens / ambers are never touched. Run: python3 scripts/gen-ui-themes.py"""
import colorsys, os

NEUTRAL = ['F6F1EA', '2A1810', '1F120C', '572C1A', 'EADFD0', 'E6DCCF', 'F7F1E8', 'FBF7F0', 'F3EDE3', 'F0E8DB', 'EFE6D8',
           'EDE4D6', '6B5A4C', 'A39484', '8A7A66', '5E4E42', '4A3A2C', 'D9CBB8', 'EFE9DC', 'D9CDB8', 'D9C4A6', 'F0E6D6',
           '6B4A2B', '8B5E34', '2E1B12', '7A5E47', '8A6A4E', '3B2A1F', '4A3426']
ACCENT = ['C9A84C', 'D9B36A', 'C5932A']
THEMES = {
    'caramel': dict(hue=29, sat=1.2, ahue=26, asat=1.1, alight=-0.02),
    'pistache': dict(hue=95, sat=0.9, ahue=90, asat=0.55, alight=-0.03),
    'bleu': dict(hue=212, sat=1.15, ahue=208, asat=0.75, alight=-0.06),
}


def rgb01(h): return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
def tohex(c): return '#%02X%02X%02X' % tuple(round(max(0, min(1, v)) * 255) for v in c)
def rgbcss(h): return 'rgb(%d, %d, %d)' % tuple(round(v * 255) for v in rgb01(h))


for th, c in THEMES.items():
    R = f'html.lp-theme-{th}'
    out = [f'/* Staff colour theme "{th}" — generated by scripts/gen-ui-themes.py, do not edit by hand. */']
    m = {}

    def emit(h, new):
        rg = rgbcss(h)
        out.append(','.join([f'{R} [style*="background-color:#{h}" i]', f'{R} [style*="background-color: #{h}" i]', f'{R} [style*="background-color: {rg}"]', f'{R} [style*=", #{h})" i]']) + f'{{background-color:{new}!important}}')
        out.append(','.join([f'{R} [style^="color:#{h}" i]', f'{R} [style*=";color:#{h}" i]', f'{R} [style*="; color: #{h}" i]', f'{R} [style^="color: {rg}"]', f'{R} [style*="; color: {rg}"]']) + f'{{color:{new}!important}}')
        out.append(','.join([f'{R} [style*="solid #{h}" i]', f'{R} [style*="solid {rg}"]', f'{R} [style*="border-color:#{h}" i]', f'{R} [style*="border-color: {rg}"]']) + f'{{border-color:{new}!important}}')
        m[h] = new

    for h in NEUTRAL:
        H, L, S = colorsys.rgb_to_hls(*rgb01(h))
        emit(h, tohex(colorsys.hls_to_rgb(c['hue'] / 360, L, min(1, S * c['sat']))))
    for h in ACCENT:
        H, L, S = colorsys.rgb_to_hls(*rgb01(h))
        emit(h, tohex(colorsys.hls_to_rgb(c['ahue'] / 360, max(0, L + c['alight']), S * c['asat'])))
    out.append(f'{R} body{{background-color:{m["F6F1EA"]}}}')
    out.append(f'{R} .bg-cream{{background-color:{m["F6F1EA"]}!important}}{R} .bg-cream-dark{{background-color:{m["EADFD0"]}!important}}{R} .bg-navy{{background-color:{m["2A1810"]}!important}}{R} .text-navy,{R} .text-ink{{color:{m["2E1B12"]}!important}}')
    out.append(f'{R} .bg-gold{{background-color:{m["C9A84C"]}!important}}{R} .text-gold{{color:{m["C9A84C"]}!important}}{R} .border-border-soft{{border-color:{m["E6DCCF"]}!important}}{R} .bg-gold-pale{{background-color:{m["FBF7F0"]}!important}}{R} .text-navy-light{{color:{m["572C1A"]}!important}}')
    out.append(f'@media (max-width:639px){{{R} .lp-station-header{{background-color:{m["F6F1EA"]}!important}}{R} .lp-station-header .lp-sync{{color:{m["572C1A"]}!important;border-color:{m["E6DCCF"]}!important}}}}')
    os.makedirs('public/ui-themes', exist_ok=True)
    open(f'public/ui-themes/{th}.css', 'w').write('\n'.join(out) + '\n')
    print(th, m['F6F1EA'], m['2A1810'], m['C9A84C'], m['6B5A4C'])
